export function getCropCatalogItem(query: string): CropCatalogItem | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  return MASTER_CROP_CATALOG.find(
    (c) =>
      c.id.toLowerCase() === q ||
      c.name.toLowerCase() === q ||
      c.name.toLowerCase().includes(q) ||
      (c.hindiName && c.hindiName.toLowerCase().includes(q)) ||
      (c.teluguName && c.teluguName.toLowerCase().includes(q))
  );
}

export function searchCrops(searchTerm: string, category?: string): CropCatalogItem[] {
  let list = MASTER_CROP_CATALOG;
  if (category && category !== "All") {
    list = list.filter((c) => c.category.toLowerCase() === category.toLowerCase());
  }
  if (!searchTerm || !searchTerm.trim()) {
    return list;
  }
  const term = searchTerm.trim().toLowerCase();
  return list.filter(
    (c) =>
      c.name.toLowerCase().includes(term) ||
      c.category.toLowerCase().includes(term) ||
      c.popularVarieties.some((v) => v.toLowerCase().includes(term)) ||
      (c.hindiName && c.hindiName.toLowerCase().includes(term)) ||
      (c.teluguName && c.teluguName.toLowerCase().includes(term))
  );
}
